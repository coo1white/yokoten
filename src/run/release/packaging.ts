// The installers a release publishes (#435): a Homebrew formula for the tap, and a Scoop
// manifest for the bucket. Both name the version and the checksum of the npm tarball, so
// a release writes them again from the packed tarball and no one edits a checksum by hand.
//
// The tarball that `npm pack` writes is the one npm publishes, so its sha256 is the one
// the formula and the manifest need. Nothing here reaches GitHub: `scripts/release/packaging.ts`
// writes the files, and a person or the release workflow copies them to the two repos.

import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

/** The published npm tarball: its version, and its sha256 in lowercase hex. */
export interface ReleaseInput {
  version: string;
  sha256: string;
}

/** One file a release writes, by its path from the output folder. */
export interface ReleaseFile {
  path: string;
  text: string;
}

/** An npm and SemVer version, such as `1.2.3` or `0.1.0-beta.1`. */
const VERSION = /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/;
/** `shasum -a 256` prints 64 lowercase hex characters. */
const SHA256 = /^[0-9a-f]{64}$/;

/** The version and checksum that are not ready for a release; empty when both are. */
export function findReleaseProblems({ version, sha256 }: ReleaseInput): string[] {
  const problems: string[] = [];
  if (!VERSION.test(version)) problems.push(`version "${version}" is not a release version like 1.2.3; read it from package.json, with no leading v`);
  if (!SHA256.test(sha256)) problems.push(`sha256 "${sha256}" is not 64 lowercase hex characters; run \`shasum -a 256\` on the packed tarball`);
  return problems;
}

/** The sha256 of a file, lowercase hex, as `shasum -a 256` prints it. */
export function sha256OfFile(path: string): string {
  return createHash('sha256').update(readFileSync(path)).digest('hex');
}

/**
 * The Homebrew formula, for `Formula/yokoten.rb` in yokoten-labs/homebrew-tap. It depends
 * on node and installs the published npm package into libexec, which is the shape
 * `brew create --node` gives: `std_npm_args` re-packs the tarball with no scripts, so the
 * `prepack` build never runs on a user's machine, and `dist/` comes from the package.
 */
export function renderHomebrewFormula({ version, sha256 }: ReleaseInput): string {
  return `# Generated by scripts/release/packaging.ts for yokoten-labs/homebrew-tap.
# A release writes it again; do not edit it by hand.
class Yokoten < Formula
  desc "Rules, guards and skills for AI coding agents"
  homepage "https://yokoten.app"
  url "https://registry.npmjs.org/yokoten/-/yokoten-${version}.tgz"
  sha256 "${sha256}"
  license "MIT"

  depends_on "node"

  def install
    system "npm", "install", *std_npm_args
    bin.install_symlink libexec.glob("bin/*")
  end

  def caveats
    <<~EOS
      Run \`yokoten install\` once to add the skills, agents and hooks to this machine.
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/yokoten --version")
    assert_match "yokoten init", shell_output("#{bin}/yokoten help")
  end
end
`;
}

/**
 * The Scoop manifest, for `bucket/yokoten.json` in yokoten-labs/scoop-bucket. Scoop
 * installs Node for it, unpacks the npm tarball and runs npm with `--ignore-scripts`, so
 * the launcher is npm's own `yokoten.cmd` and nothing runs a build on the user's machine.
 */
export function renderScoopManifest({ version, sha256 }: ReleaseInput): string {
  const manifest = {
    version,
    description: 'Rules, guards and skills for AI coding agents.',
    homepage: 'https://yokoten.app',
    license: 'MIT',
    depends: 'nodejs',
    url: `https://registry.npmjs.org/yokoten/-/yokoten-${version}.tgz`,
    hash: `sha256:${sha256}`,
    extract_dir: 'package',
    installer: {
      script: [
        'npm install --global --ignore-scripts --prefix "$dir" "$dir"',
        'if (!(Test-Path "$dir\\yokoten.cmd")) { throw "npm wrote no yokoten.cmd: is Node on PATH?" }',
      ],
    },
    bin: 'yokoten.cmd',
    notes: ['Run `yokoten install` once to add the skills, agents and hooks.'],
    checkver: {
      url: 'https://registry.npmjs.org/yokoten/latest',
      jsonpath: '$.version',
    },
  };
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

/** Every file a release writes, in a stable order, with valid input. */
export function renderReleaseFiles(input: ReleaseInput): ReleaseFile[] {
  return [
    { path: 'homebrew-tap/Formula/yokoten.rb', text: renderHomebrewFormula(input) },
    { path: 'scoop-bucket/bucket/yokoten.json', text: renderScoopManifest(input) },
  ];
}

/**
 * Write the release files under `outDir`, one sub-folder per repo, so each is one `cp -r`
 * away from the tap or the bucket. Refuses bad input before it writes anything.
 */
export function writeReleaseFiles(input: ReleaseInput, outDir: string): ReleaseFile[] {
  const problems = findReleaseProblems(input);
  if (problems.length) throw new Error(problems.join('\n'));
  const files = renderReleaseFiles(input);
  for (const file of files) {
    const path = join(outDir, file.path);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, file.text);
  }
  return files;
}
